/**
 * The ChatGPT course's six levels, each a list of authored lessons.
 *
 * Server-only, for the same reason the lesson bodies are: the browser needs a
 * lesson's id, title, length and type to draw the roadmap and never needs the
 * prose or the answers. The client-safe skeleton is generated from this file
 * into `chatgpt-course.gen.ts` — regenerate it with `bun run lessons:manifest`.
 *
 * Levels used to be lists of task specs rendered through one shared wrapper,
 * which stamped each level's guide, safety note and reference onto all ten of
 * its pages — about seven tenths of what a learner read on any one of them.
 * All six are now written as lessons and the wrapper is gone.
 */
import type { AuthoredLesson } from "./authored-lesson";
import { chatgptAutonomyLessons } from "./chatgpt-autonomy.server";
import { chatgptContextLessons } from "./chatgpt-context.server";
import { chatgptFilesLessons } from "./chatgpt-files.server";
import { chatgptPromptingLessons } from "./chatgpt-prompting.server";
import { chatgptResearchLessons } from "./chatgpt-research.server";
import { chatgptWorkflowsLessons } from "./chatgpt-workflows.server";
import type { ModuleMeta } from "./curriculum";

export type ChatGPTLevel = {
  id: string;
  title: string;
  summary: string;
  lessons: AuthoredLesson[];
};

/** The one definition of a lesson's id, so the skeleton and the bodies agree. */
export const chatgptLessonId = (levelId: string, slug: string) => `${levelId}.${slug}`;

export const chatgptLevels: ChatGPTLevel[] = [
  {
    id: "chatgpt-prompting",
    title: "Level 1 · Clear Prompts",
    summary: "Turn ordinary questions into useful, checkable requests.",
    lessons: chatgptPromptingLessons,
  },
  {
    id: "chatgpt-context",
    title: "Level 2 · Context & Working Briefs",
    summary: "Give ChatGPT the right information and carry decisions between sessions.",
    lessons: chatgptContextLessons,
  },
  {
    id: "chatgpt-research",
    title: "Level 3 · Research & Verification",
    summary: "Turn questions and sources into defensible conclusions.",
    lessons: chatgptResearchLessons,
  },
  {
    id: "chatgpt-files",
    title: "Level 4 · Files, Data & Deliverables",
    summary: "Create useful outputs and verify their contents yourself.",
    lessons: chatgptFilesLessons,
  },
  {
    id: "chatgpt-workflows",
    title: "Level 5 · Reusable Workflows & Tools",
    summary: "Package repeatable work with clear inputs, outputs, and review steps.",
    lessons: chatgptWorkflowsLessons,
  },
  {
    id: "chatgpt-autonomy",
    title: "Level 6 · Bounded Autonomy",
    summary: "Delegate a complete task with limits, verification, and a clear stopping point.",
    lessons: chatgptAutonomyLessons,
  },
];

/**
 * The client-safe course skeleton: ids, titles, lengths and types, and nothing
 * a learner could read an answer out of.
 */
export function chatgptModulesFromLevels(): ModuleMeta[] {
  return chatgptLevels.map((level) => ({
    id: level.id,
    title: level.title,
    summary: `${level.lessons.length} lessons · ${level.summary}`,
    lessons: level.lessons.map((lesson) => ({
      id: chatgptLessonId(level.id, lesson.slug),
      title: lesson.title,
      minutes: lesson.minutes,
      type: lesson.type,
    })),
  }));
}

export function renderChatGPTModules(): string {
  return `// AUTO-GENERATED by \`bun run lessons:manifest\` from chatgpt-levels.server.ts — never edit.
import type { ModuleMeta } from "./curriculum";

export const chatgptModules: ModuleMeta[] = ${JSON.stringify(chatgptModulesFromLevels(), null, 2)};
`;
}
