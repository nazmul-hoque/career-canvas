/**
 * The second SQL dataset: two years of daily sales from a small chain of
 * outdoor-gear stores and its website. Lessons about dates, LAG and
 * period-over-period change run against it, because the shop's 15 orders are
 * too few to bucket by month or compare one period with the last. A challenge
 * opts in with `dataset: "stores"`.
 *
 * It is a separate business, not the shop grown up: a daily table for the same
 * shop would contradict its orders table by two orders of magnitude, and the
 * course that teaches reconciling numbers can't ship tables that don't.
 *
 * The rows are generated by the SQL below rather than listed, which keeps a
 * 1,611-row table small enough to ship with every SQL run. The noise comes
 * from a quadratic hash with a prime period longer than the table, so it never
 * lines up with the weekday. Built in, because they are what make date work go
 * wrong:
 *
 * - Leeds is closed on Sundays and both stores on 25–26 December and 1 January:
 *   those days have no row at all, so seven rows are not seven days.
 * - The website was down 10–12 June 2025, also with no rows.
 * - Leeds stayed open through the snow on 8 January 2025 and sold nothing: a row
 *   that says 0, which is different from a missing one.
 * - Harrogate opened on 12 April 2025, so it has no 2024 to compare with.
 * - Seasonality (a summer peak, a January dip), Black Friday on the website,
 *   and roughly 15% growth from 2024 to 2025.
 *
 * Lessons quote its numbers, so changing the generator means re-checking every
 * lesson that uses it — `bun run lessons:verify` re-runs their tests.
 */
export const STORES_SCHEMA = `stores      (id, name, channel, city, opened_on)
daily_sales (day, store_id, orders, revenue)`;

export const STORES_SQL = `
CREATE TABLE stores (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  channel TEXT NOT NULL,
  city TEXT,
  opened_on TEXT NOT NULL
);
INSERT INTO stores VALUES
  (1, 'Website', 'web', NULL, '2022-03-01'),
  (2, 'Leeds', 'store', 'Leeds', '2019-09-14'),
  (3, 'Harrogate', 'store', 'Harrogate', '2025-04-12');

CREATE TABLE daily_sales (
  day TEXT NOT NULL,
  store_id INTEGER NOT NULL REFERENCES stores(id),
  orders INTEGER NOT NULL,
  revenue REAL NOT NULL,
  PRIMARY KEY (day, store_id)
);
INSERT INTO daily_sales
WITH RECURSIVE days(n, day) AS (
  SELECT 0, '2024-01-01'
  UNION ALL
  SELECT n + 1, date(day, '+1 day') FROM days WHERE day < '2025-12-31'
),
open_days AS (
  SELECT d.n, d.day, s.id AS store_id,
         CAST(strftime('%m', d.day) AS INTEGER) AS m,
         CAST(strftime('%w', d.day) AS INTEGER) AS w
  FROM days AS d
  JOIN stores AS s ON d.day >= s.opened_on
  WHERE NOT (s.channel = 'store' AND substr(d.day, 6) IN ('12-25', '12-26', '01-01'))
    AND NOT (s.id = 2 AND strftime('%w', d.day) = '0')
    AND NOT (s.id = 1 AND d.day BETWEEN '2025-06-10' AND '2025-06-12')
),
volumes AS (
  SELECT n, day, store_id,
         MAX(1, CAST(ROUND(
             CASE store_id WHEN 1 THEN 14 WHEN 2 THEN 10 ELSE 7 END
           * CASE m WHEN 1 THEN 0.7 WHEN 2 THEN 0.75 WHEN 3 THEN 0.9 WHEN 4 THEN 1.05
                    WHEN 5 THEN 1.15 WHEN 6 THEN 1.3 WHEN 7 THEN 1.35 WHEN 8 THEN 1.2
                    WHEN 9 THEN 1.0 WHEN 10 THEN 0.95 WHEN 11 THEN 1.1 ELSE 1.25 END
           * CASE WHEN day >= '2025-01-01' THEN 1.15 ELSE 1.0 END
           * CASE WHEN store_id = 1 AND w IN (0, 6) THEN 1.2
                  WHEN store_id > 1 AND w = 6 THEN 1.6 ELSE 1.0 END
           * CASE WHEN store_id = 1 AND day IN ('2024-11-29', '2025-11-28') THEN 3
                  WHEN store_id = 3 AND day = '2025-04-12' THEN 2.5 ELSE 1 END
         ) AS INTEGER) + (n * n * 7919 + n * 104729 + store_id * 31) % 1009 * 7 / 1009 - 3) AS orders,
         CASE store_id WHEN 1 THEN 52 ELSE 64 END
           + (n * n * 6151 + n * 3079 + store_id * 17) % 1013 * 21 / 1013 AS basket
  FROM open_days
)
SELECT day, store_id,
       CASE WHEN day = '2025-01-08' AND store_id = 2 THEN 0 ELSE orders END,
       CASE WHEN day = '2025-01-08' AND store_id = 2 THEN 0.0 ELSE orders * basket * 1.0 END
FROM volumes
ORDER BY day, store_id;
`;
