import { bodies } from "./lesson-bodies.server";
import { manifestEntry } from "./lessons";

/**
 * Renders the manifest file from the authored lessons. Used by
 * scripts/build-lesson-manifest.ts and by the test that checks the committed
 * file is current — never by the app, since it reads the server-only bodies.
 */
export function renderManifest(): string {
  const rows = Object.entries(bodies)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, body]) => {
      const { challenge, questions, attested } = manifestEntry(body);
      const fields = `challenge: ${challenge}, questions: ${questions}${attested ? ", attested: true" : ""}`;
      return `  "${id}": { ${fields} },`;
    });
  return `// AUTO-GENERATED by \`bun run lessons:manifest\` from lesson-bodies.server.ts — never edit.
import type { LessonManifestEntry } from "./lessons";

export const lessonManifest: Record<string, LessonManifestEntry> = {
${rows.join("\n")}
};
`;
}
