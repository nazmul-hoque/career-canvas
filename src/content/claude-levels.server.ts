/**
 * The Claude course's six levels, each a list of authored lessons.
 *
 * Server-only, for the same reason the lesson bodies are. The browser needs a
 * lesson's id, title, length and type to draw the roadmap; it never needs the
 * prose, which would otherwise sit in the main client chunk on the first-paint
 * path of every route that imports the curriculum. The client-safe skeleton is
 * generated from this file into `claude-course.gen.ts` — regenerate it with
 * `bun run lessons:manifest`.
 *
 * Levels used to be lists of task specs rendered through one shared wrapper,
 * which stamped the level's guide, safety note and reference onto every page.
 * All six have now been rewritten as lessons, so the wrapper and the union that
 * kept both forms legal during the migration are gone with it.
 */
import type { AuthoredLesson } from "./authored-lesson";
import { claudeAutonomyLessons } from "./claude-autonomy.server";
import { claudeCliLessons } from "./claude-cli.server";
import { claudePromptingLessons } from "./claude-prompting.server";
import { claudeSkillsSafetyLessons } from "./claude-skills-safety.server";
import { claudeSubagentsLessons } from "./claude-subagents.server";
import { claudeToolsLessons } from "./claude-tools.server";
import type { ModuleMeta } from "./curriculum";

export type ClaudeLevelDefinition = {
  id: string;
  title: string;
  summary: string;
  lessons: AuthoredLesson[];
};

/**
 * The one definition of a lesson's id. The course modules and the bodies in
 * `claude-lessons.server.ts` both derive their keys from it, so a lesson cannot
 * go dark because two copies of the formula drifted apart. Keyed by slug rather
 * than position: merging tasks into lessons renumbers everything after the
 * first change, and a positional id would quietly point at different content.
 */
export const claudeLessonId = (levelId: string, slug: string) => `${levelId}.${slug}`;

export const claudeLevels: ClaudeLevelDefinition[] = [
  {
    id: "claude-prompting",
    title: "Level 1 · Basic Prompting",
    summary: "Ask useful questions, shape the answer, and check it before you use it.",
    lessons: claudePromptingLessons,
  },
  {
    id: "claude-cli",
    title: "Level 2 · Claude CLI",
    summary: "Work with Claude Code in a terminal, from a first session to repeatable commands.",
    lessons: claudeCliLessons,
  },
  {
    id: "claude-tools",
    title: "Level 3 · Tools",
    summary: "Connect Claude to outside services with MCP while keeping access narrow and visible.",
    lessons: claudeToolsLessons,
  },
  {
    id: "claude-subagents",
    title: "Level 4 · Subagents",
    summary: "Delegate focused work to specialist Claude workers and combine their results.",
    lessons: claudeSubagentsLessons,
  },
  {
    id: "claude-skills-safety",
    title: "Level 5 · Skills & Safety",
    summary: "Package repeatable expertise into skills and design permissions that fail safely.",
    lessons: claudeSkillsSafetyLessons,
  },
  {
    id: "claude-autonomy",
    title: "Level 6 · Autonomy",
    summary: "Build bounded, observable workflows that can run without constant supervision.",
    lessons: claudeAutonomyLessons,
  },
];

/**
 * The client-safe course skeleton: ids, titles, lengths and types, and nothing
 * a learner could read an answer out of. `claude-course.gen.ts` is this value
 * written to disk; the test compares the two so the committed file cannot drift.
 */
export function claudeModulesFromLevels(): ModuleMeta[] {
  return claudeLevels.map((level) => ({
    id: level.id,
    title: level.title,
    summary: `${level.lessons.length} lessons \u00b7 ${level.summary}`,
    lessons: level.lessons.map((lesson) => ({
      id: claudeLessonId(level.id, lesson.slug),
      title: lesson.title,
      minutes: lesson.minutes,
      type: lesson.type,
    })),
  }));
}

export function renderClaudeModules(): string {
  return `// AUTO-GENERATED by \`bun run lessons:manifest\` from claude-levels.server.ts — never edit.
import type { ModuleMeta } from "./curriculum";

export const claudeModules: ModuleMeta[] = ${JSON.stringify(claudeModulesFromLevels(), null, 2)};
`;
}
